[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)][string]$AddOnsPath,
    [Parameter(Mandatory = $true)][ValidateRange(1, 3)][int]$Slot,
    [Parameter(Mandatory = $true)][ValidatePattern('\A[A-Za-z0-9_-]{1,48}\z')][string]$Marker
)
$ErrorActionPreference = 'Stop'
# This is a one-shot writer, not a watcher, installer, or network bridge.
$root = Get-Item -LiteralPath $AddOnsPath
if (-not $root.PSIsContainer) { throw 'AddOnsPath must be an existing directory.' }
$addon = 'CallToArmsProbeSnapshot{0:D2}' -f $Slot
$folder = Get-Item -LiteralPath (Join-Path $root.FullName $addon)
$toc = Get-Item -LiteralPath (Join-Path $folder.FullName "$addon.toc")
$target = Get-Item -LiteralPath (Join-Path $folder.FullName 'Snapshot.lua')
foreach ($item in @($folder, $toc, $target)) {
    if ($item.Attributes -band [IO.FileAttributes]::ReparsePoint) { throw 'Snapshot paths must not be links or junctions.' }
}
if (-not $folder.PSIsContainer -or $toc.PSIsContainer -or $target.PSIsContainer) {
    throw 'Expected an installed slot directory containing its TOC and Snapshot.lua.'
}
$tocText = [IO.File]::ReadAllText($toc.FullName)
if ($tocText -notmatch '(?m)^## LoadOnDemand: 1\r?$' -or
    $tocText -notmatch '(?m)^Snapshot\.lua\r?$') {
    throw 'This is not an expected preinstalled snapshot slot.'
}
$written = [DateTime]::UtcNow.ToString('o')
# Marker is deliberately restricted to a Lua-safe literal; no arbitrary code input.
$content = @"
-- CTA diagnostic snapshot. Generated by Write-Snapshot.ps1; not SavedVariables.
CallToArmsProbeSnapshots = CallToArmsProbeSnapshots or {}
local name = "$addon"
local previous = CallToArmsProbeSnapshots[name]
CallToArmsProbeSnapshots[name] = {
    marker = "$Marker",
    writtenUtc = "$written",
    executions = (previous and previous.executions or 0) + 1,
}
"@
$temp = Join-Path $folder.FullName ('.cta-snapshot-' + [Guid]::NewGuid().ToString('N') + '.tmp')
try {
    [IO.File]::WriteAllText($temp, $content + "`n", [Text.UTF8Encoding]::new($false))
    # Replace a complete file in the same directory; never expose a partial Lua file.
    [IO.File]::Replace($temp, $target.FullName, [NullString]::Value)
} finally {
    if (Test-Path -LiteralPath $temp) { Remove-Item -LiteralPath $temp }
}
[pscustomobject]@{
    Slot = $Slot
    Marker = $Marker
    WrittenUtc = $written
    Path = $target.FullName
    SHA256 = (Get-FileHash -LiteralPath $target.FullName -Algorithm SHA256).Hash
} | Format-List
Write-Output ('In WoW, without reload/relog: /ctaprobe snapshot load {0:D2} {1}' -f $Slot, $Marker)
Write-Output 'This confirms a disk write only. Export the in-game log to determine what WoW loaded.'
